#!/usr/bin/env bash
# Собирает папку dist — то, и только то, что должно уехать на сайт.
#
# Список белый, не чёрный: что здесь не названо, наружу не попадёт.
# Причина конкретная. 21 августа 2026 выяснилось, что боевой адрес отдаёт
# CLAUDE.md, STATE.md, OPEN_QUESTIONS.md и папку .claude — то есть весь
# рабочий разбор проекта, включая внутренние заметки про цены и заглушки,
# мог прочитать любой, кто угадает имя файла. Чёрный список такое ловит
# через раз: добавил новый документ — и забыл его вписать.
#
# Карточки цен для своих (og/tseny-*.jpg) сюда не входят намеренно:
# их отправляют в переписке, хостить их незачем.
set -euo pipefail
cd "$(dirname "$0")/.."

rm -rf dist
mkdir -p dist/og

cp index.html robots.txt sitemap.xml _headers dist/
cp -R img vid font dist/
cp og/kadr.jpg dist/og/

# защита от тихой поломки: без главной страницы выкатывать нечего
test -s dist/index.html || { echo "нет dist/index.html — сборка сорвалась"; exit 1; }

echo "собрано: $(find dist -type f | wc -l | tr -d ' ') файлов, $(du -sh dist | cut -f1)"
